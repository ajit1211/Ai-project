"""SQLAlchemy Core definitions of the agent tables (apps/core/nexa_core/agents/models.py).

Core owns the schema; Runtime reads agents and writes runs and steps (granted by
`agents/0002_tenant_fks_and_runtime_grants`).
"""

from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    DateTime,
    Integer,
    MetaData,
    SmallInteger,
    String,
    Table,
    Text,
    Uuid,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB

metadata = MetaData()

agents = Table(
    "agents",
    metadata,
    Column("id", Uuid, primary_key=True),
    Column("organization_id", Uuid),
    Column("created_by_id", Uuid),
    Column("name", String, nullable=False),
    Column("slug", String, nullable=False),
    Column("description", String, nullable=False),
    Column("instructions", Text, nullable=False),
    Column("version", Integer, nullable=False),
    Column("enabled", Boolean, nullable=False),
    Column("is_system", Boolean, nullable=False),
    Column("model", String, nullable=False),
    Column("allowed_tools", ARRAY(String), nullable=False),
    Column("input_schema", JSONB(none_as_null=True)),
    Column("output_schema", JSONB(none_as_null=True)),
    Column("max_steps", SmallInteger, nullable=False),
    Column("max_tool_calls", SmallInteger, nullable=False),
    Column("max_duration_seconds", Integer, nullable=False),
    Column("max_tokens", Integer, nullable=False),
    Column("approval_policy", String, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False),
    Column("updated_at", DateTime(timezone=True), nullable=False),
    Column("deleted_at", DateTime(timezone=True)),
)

agent_runs = Table(
    "agent_runs",
    metadata,
    Column("id", Uuid, primary_key=True),
    Column("organization_id", Uuid, nullable=False),
    Column("agent_id", Uuid, nullable=False),
    Column("agent_version", Integer, nullable=False),
    Column("agent_snapshot", JSONB, nullable=False),
    Column("user_id", Uuid, nullable=False),
    Column("conversation_id", Uuid),
    Column("goal", Text, nullable=False),
    Column("input", JSONB, nullable=False),
    Column("status", String, nullable=False),
    Column("failure_reason", String, nullable=False),
    Column("error_message", String, nullable=False),
    Column("progress_message", String, nullable=False),
    Column("model", String, nullable=False),
    Column("step_count", Integer, nullable=False),
    Column("model_calls", Integer, nullable=False),
    Column("tool_call_count", Integer, nullable=False),
    Column("input_tokens", Integer, nullable=False),
    Column("output_tokens", Integer, nullable=False),
    Column("cost_micros", BigInteger),
    Column("result", Text, nullable=False),
    Column("output", JSONB(none_as_null=True)),
    Column("sources", JSONB, nullable=False),
    Column("cancel_requested", Boolean, nullable=False),
    Column("pause_requested", Boolean, nullable=False),
    Column("claimed_by", String, nullable=False),
    Column("lease_expires_at", DateTime(timezone=True)),
    Column("attempts", SmallInteger, nullable=False),
    Column("idempotency_key", String, nullable=False),
    Column("request_id", String, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False),
    Column("started_at", DateTime(timezone=True)),
    Column("updated_at", DateTime(timezone=True), nullable=False),
    Column("completed_at", DateTime(timezone=True)),
    Column("deadline_at", DateTime(timezone=True)),
    Column("time_left_seconds", Integer),
)

agent_steps = Table(
    "agent_steps",
    metadata,
    Column("id", Uuid, primary_key=True),
    Column("organization_id", Uuid, nullable=False),
    Column("run_id", Uuid, nullable=False),
    Column("sequence", Integer, nullable=False),
    Column("kind", String, nullable=False),
    Column("status", String, nullable=False),
    Column("summary", String, nullable=False),
    Column("detail", JSONB, nullable=False),
    Column("invocation_id", Uuid),
    Column("error_code", String, nullable=False),
    Column("retry_count", SmallInteger, nullable=False),
    Column("input_tokens", Integer, nullable=False),
    Column("output_tokens", Integer, nullable=False),
    Column("usage_event_id", Uuid),
    Column("started_at", DateTime(timezone=True)),
    Column("finished_at", DateTime(timezone=True)),
    Column("duration_ms", Integer),
    Column("created_at", DateTime(timezone=True), nullable=False),
)
